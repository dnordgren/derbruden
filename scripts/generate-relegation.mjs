// Divisional relegation backtest. Counterfactual model for the league
// vote proposal: divisions rebased every year from prior-year results
// (Division A = prior year's top 5, Division B = bottom 5), divisional
// opponents played twice, everyone else once.
//
// Method: a team's fantasy score in a week does not depend on its
// opponent, so each season's actual weekly scores (ESPN mMatchupScore,
// regular season only) are held fixed and only the pairings change.
// Standings, margins, and playoff fields are recomputed under the new
// schedule and compared with what actually happened.
//
//   node scripts/generate-relegation.mjs [--offline]
//
// Reads scripts/.relegation-cache/season-<year>.json when present
// (git-ignored), otherwise fetches from ESPN and fills the cache;
// --offline fails instead of fetching. Writes
// static/data/relegation.json and docs/relegation-backtest.md.
//
// Backtest window: target seasons 2019-2025, each seeded from the
// prior season (2018 is the first ESPN season, so it can only seed).
// Seeding metric is prior-year All-Play % (schedule-independent, so a
// recursive re-seed changes nothing), tie-broken by points for. A
// sensitivity pass seeds by prior-year W-L instead.
// 2021-2022 were 14-week regular seasons: week 14 uses one extra
// cross-division round (see WEEK_14), flagged in the output.

