export function parseEdgeLocation(raw) {
  if (!raw || raw === '-') return null
  const match = /^([A-Z]{3})/.exec(String(raw).trim().toUpperCase())
  if (!match) return null
  const code = match[1]
  const found = EDGE_LOCATIONS[code]
  return found ? { code, city: found.city, country: found.country } : { code, city: code, country: 'Unknown' }
}
